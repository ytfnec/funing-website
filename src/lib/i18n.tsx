export type TKey = keyof typeof translations['en'];

// Exposed for admin tools (e.g. content-block preview) to read default copy.
export const defaultTranslations = translations;

const LanguageContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
}>({
  lang: 'zh',
  setLang: () => {},
  t: (k) => k as string,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>('zh');
  const [overrides, setOverrides] = useState<Record<string, string>>({});

  useEffect(() => {
    const saved = localStorage.getItem('fnec-lang') as Lang | null;
    if (saved === 'en' || saved === 'zh') {
      setLang(saved);
      document.documentElement.lang = saved === 'zh' ? 'zh-CN' : 'en';
    } else {
      const nav = (navigator.language || 'zh').toLowerCase();
      const detected: Lang = nav.startsWith('zh') ? 'zh' : 'en';
      setLang(detected);
      document.documentElement.lang = detected === 'zh' ? 'zh-CN' : 'en';
    }
  }, []);

  // Fetch content-block overrides (managed via /admin/content) so edits
  // to copy take effect on the live site without redeploying.
  useEffect(() => {
    let cancelled = false;
    fetch('/api/content')
      .then((res) => (res.ok ? res.json() : { overrides: {} }))
      .then((data) => {
        if (!cancelled) setOverrides(data.overrides || {});
      })
      .catch(() => {
        // Fail soft — site renders default translations.
      });
    return () => {
      cancelled = true;
    };
  }, []);

  const changeLang = (l: Lang) => {
    setLang(l);
    localStorage.setItem('fnec-lang', l);
    document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
  };

  // Look up overrides first (`<lang>__<key>`), then default translations.
  const t = (k: TKey) => {
    const overrideKey = `${lang}__${k}`;
    if (overrides[overrideKey]) return overrides[overrideKey];
    return translations[lang][k] ?? translations.en[k] ?? String(k);
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang: changeLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  return useContext(LanguageContext);
}

export function LanguageSwitcher() {
  const { lang, setLang } = useLang();
  return (
    <div className="flex items-center gap-1 border border-[rgba(255,255,255,0.15)] rounded-full px-1 py-0.5">
      <button
        type="button"
        onClick={() => setLang('zh')}
        className={`text-[11px] tracking-[0.08em] rounded-full px-2.5 py-1 transition-colors ${
          lang === 'zh' ? 'bg-[var(--amber)] text-[#050505] font-bold' : 'text-[var(--gray)] hover:text-white'
        }`}
      >
        中文
      </button>
      <button
        type="button"
        onClick={() => setLang('en')}
        className={`text-[11px] tracking-[0.08em] rounded-full px-2.5 py-1 transition-colors ${
          lang === 'en' ? 'bg-[var(--amber)] text-[#050505] font-bold' : 'text-[var(--gray)] hover:text-white'
        }`}
      >
        EN
      </button>
    </div>
  );
}
