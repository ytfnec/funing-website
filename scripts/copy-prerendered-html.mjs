// Copy Next.js prerendered static HTML from .next/server/app into the
// OpenNext assets output so Cloudflare Static Assets serves them directly,
// bypassing the Worker entirely for static routes (free-tier 1102 mitigation).
//
// Cloudflare Static Assets URL mapping (run_worker_first: false — the default):
//   /about      -> about.html   (or about/index.html)
//   /           -> index.html
//   /admin/login -> admin/login.html
//
// Only copies routes that are NOT dynamic (no [param] segments). Dynamic routes
// (products/[slug], news/[slug]) and API routes are served by the Worker as usual.
import { cpSync, readdirSync, existsSync, mkdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';

const serverAppDir = '.next/server/app';
const assetsDir = '.open-next/assets';

if (!existsSync(serverAppDir)) {
  console.error('ERROR: .next/server/app not found. Run next build / build:cf first.');
  process.exit(1);
}
if (!existsSync(assetsDir)) {
  console.error('ERROR: .open-next/assets not found. Run build:cf first.');
  process.exit(1);
}

const skipDirs = new Set(['[slug]', 'api']);
const copied = [];
const skipped = [];

function shouldSkip(relPath) {
  return relPath.split(/[\\/]/).some((seg) => skipDirs.has(seg));
}

function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    const rel = relative(serverAppDir, abs);
    if (entry.isDirectory()) {
      // Only skip [slug]/api; always recurse otherwise
      walk(abs);
    } else if (entry.isFile() && entry.name.endsWith('.html')) {
      if (shouldSkip(rel)) {
        skipped.push(rel);
        continue;
      }
      // Map .next/server/app/<route>.html -> assets/<route>.html
      // Root route: .next/server/app/index.html -> assets/index.html
      const destRel = rel;
      const destAbs = join(assetsDir, destRel);
      mkdirSync(dirname(destAbs), { recursive: true });
      cpSync(abs, destAbs);
      copied.push(destRel);
    }
  }
}

walk(serverAppDir);

// Write a _headers file so Cloudflare Static Assets applies cache + security
// headers to the served HTML (headers set in next.config.js don't apply to
// static assets bypassing the Worker).
// - Public HTML: cache 300s at edge + 1h stale-while-revalidate (same as the
//   Worker path used before, so behaviour is unchanged for cached pages).
// - Admin HTML shells: also cacheable (shell contains no session data; auth is
//   enforced client-side via /api/auth).
const headersFile = join(assetsDir, '_headers');
const headers = `# Auto-generated by scripts/copy-prerendered-html.mjs (build:cf:static)
/*
  X-Frame-Options: SAMEORIGIN
  X-Content-Type-Options: nosniff
  Cache-Control: public, max-age=0, s-maxage=300, stale-while-revalidate=3600

`;
writeFileSync(headersFile, headers, 'utf8');

console.log(`\nCopied ${copied.length} prerendered HTML files into .open-next/assets:`);
for (const f of copied) console.log('  +', f);
if (skipped.length) {
  console.log(`\nSkipped ${skipped.length} dynamic/api HTML files (Worker will serve them):`);
  for (const f of skipped) console.log('  -', f);
}
console.log(`\nWrote ${headersFile}`);

